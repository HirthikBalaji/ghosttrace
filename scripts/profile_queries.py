"""PROFILE the hot queries on the seeded Ghost Credential workspace and time them (docs/performance.md)."""

import statistics
import sys
import time
from pathlib import Path

sys.path[:0] = [str(Path(__file__).resolve().parents[1] / "backend"), str(Path(__file__).resolve().parents[1])]
from app.graph import queries as Q  # noqa: E402
from app.graph.client import GraphClient  # noqa: E402
from app.graph.repository import Repository  # noqa: E402
from app.ingestion.seed import seed  # noqa: E402
from app.model import ALL_FACT_EDGE_TYPES, TrustPolicy  # noqa: E402
from app.planner import engine  # noqa: E402

c = GraphClient()
ws = "profile"
seed(c, ws, "ghost_credential_a")
repo = Repository(c, ws)
w = repo.world()
now = w.meta["now"]
allowed = [e.edge_id for e in engine.snapshot_edges(w, now, now, TrustPolicy.CONSERVATIVE)]
cases = {
    "active snapshot (bitemporal predicate)": (
        Q.ACTIVE_EDGE_VERSIONS,
        {"ws": ws, "types": list(ALL_FACT_EDGE_TYPES), "T": now, "tau": now},
    ),
    "attack path enumeration depth 8": (
        Q.FIND_PATHS[8],
        {"ws": ws, "sources": w.attack_sources, "targets": w.targets, "allowed": allowed, "T": now, "tau": now, "limit": 500},
    ),
    "as-of ownership": (Q.OWNERS, {"ws": ws, "sid": "svc:payments-api", "T": now, "tau": now}),
    "memory retrieval by graph relevance": (
        Q.RELEVANT_MEMORY,
        {"ws": ws, "entity_ids": ["id:dev-alice", "inc:INC-2025-0912"], "source_ids": ["src:idp-signin"], "limit": 20},
    ),
}
out = []
for name, (q, p) in cases.items():
    ts = []
    for _ in range(30):
        t0 = time.perf_counter()
        c.ro(ws, q, p)
        ts.append((time.perf_counter() - t0) * 1000)
    s = sorted(ts)
    out.append(
        f"## {name}\n\nclient round-trip ms over 30 runs: median {statistics.median(s):.2f}, p95 {s[int(0.95 * 29)]:.2f}\n"
    )
    out.append("```\n" + c.profile(ws, q, p) + "\n```\n")
c.drop_workspace(ws)
Path(__file__).resolve().parents[1].joinpath("docs", "performance-profiles.md").write_text(
    "# Query profiles (generated by scripts/profile_queries.py)\n\nSynthetic Ghost Credential workspace; local FalkorDB "
    "v4.22.0 in Docker on the development laptop (Apple Silicon). Numbers are client round-trip times.\n\n" + "\n".join(out)
)
print("\n".join(x.splitlines()[0] + " " + x.splitlines()[2] for x in out[::2]))
